BaseballLeague = Literal["MLB", "NPB"]
BaseballSubLeague = Literal["AL", "NL", "INTERLEAGUE_MLB", "CL", "PL", "KORYUSEN"]
RoofType = Literal["fixed_dome", "retractable", "outdoor"]


class BallparkMetadata(BaseModel):
    """Geographic, roof, and multi-year rolling park-factor metadata for a baseball stadium."""

    model_config = ConfigDict(frozen=True)

    venue_id: str
    venue_name: str
    league: BaseballLeague
    primary_team: str | None = None
    latitude: float
    longitude: float
    timezone: str
    roof_type: RoofType = "outdoor"
    is_neutral_or_regional: bool = False
    run_factor: float = 1.00
    hr_factor_lhb: float = 1.00
    hr_factor_rhb: float = 1.00

    @property
    def is_dome_or_retractable(self) -> bool:
        """Return True if the ballpark has a fixed dome or retractable roof."""
        return self.roof_type in {"fixed_dome", "retractable"}


class BaseballClubMetadata(BaseModel):
    """Canonical MLB or NPB club metadata."""

    model_config = ConfigDict(frozen=True)

    team: str
    team_name: str
    league: BaseballLeague
    sub_league: Literal["AL", "NL", "CL", "PL"]
    primary_venue_id: str
    mlb_statsapi_id: int | None = None


class LeagueSabermetricPriors(BaseModel):
    """League-specific wOBA linear weights, FIP constants, and baseline skill priors."""

    model_config = ConfigDict(frozen=True)

    league: BaseballLeague
    w_ubb: float
    w_hbp: float
    w_1b: float
    w_2b: float
    w_3b: float
    w_hr: float
    fip_constant: float
    lg_hr_per_fb: float
    lg_woba: float
    lg_iso: float
    lg_batter_k_pct: float
    lg_batter_bb_pct: float
    lg_sp_fip: float
    lg_sp_xfip: float
    lg_sp_k_pct: float
    lg_sp_bb_pct: float
    lg_sp_gb_pct: float
    lg_bp_xfip: float
    lg_runs_per_team_game: float


