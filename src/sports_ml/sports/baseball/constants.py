def normalize_baseball_team(team: str) -> str:
    """Normalize an MLB or NPB club code or name to its canonical 3-letter code."""
    cleaned_raw = " ".join(team.strip().split())
    if cleaned_raw in BASEBALL_CLUB_ALIASES:
        return BASEBALL_CLUB_ALIASES[cleaned_raw]
    cleaned_upper = cleaned_raw.upper()
    if cleaned_upper in ALL_BASEBALL_CLUBS:
        return cleaned_upper
    return BASEBALL_CLUB_ALIASES.get(cleaned_upper, cleaned_upper)


def get_baseball_club_metadata(team: str) -> BaseballClubMetadata | None:
    """Return canonical club metadata for an MLB or NPB team."""
    canonical = normalize_baseball_team(team)
    return ALL_BASEBALL_CLUBS.get(canonical)


def resolve_team_league(team: str) -> BaseballLeague | None:
    """Return 'MLB' or 'NPB' for a team code/name, or None if unknown."""
    meta = get_baseball_club_metadata(team)
    return meta.league if meta is not None else None


def get_ballpark_metadata(venue_or_team: str) -> BallparkMetadata | None:
    """Return ballpark metadata by `venue_id` or fallback to a team's `primary_venue_id`."""
    key = venue_or_team.strip().upper()
    if key in BASEBALL_BALLPARKS:
        return BASEBALL_BALLPARKS[key]
    club = get_baseball_club_metadata(key)
    if club is not None:
        return BASEBALL_BALLPARKS.get(club.primary_venue_id)
    return None


